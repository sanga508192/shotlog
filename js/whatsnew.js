// a ใหม่กว่า b ไหม (เทียบเลขรุ่น x.y.z)
export function newer(a, b) {
  if (!b) return true;
  const pa = String(a).split('.').map(Number), pb = String(b).split('.').map(Number);
  for (let i = 0; i < 3; i++) if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) > (pb[i] || 0);
  return false;
}

